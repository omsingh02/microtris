; tinytris's design: one word per board row, a piece is a 4x4 bit mask, one routine tests, stamps and erases by
; patching its own opcode, the answer comes back in ZF, a rejected move is undone from the stack, the whole board is
; redrawn every pass. Different here: rotation gathers one column of the mask per multiply, a piece is one byte in
; the table (two rows of its box), a cell's colour comes from the flags (lahf), the board starts at offset 0, and the
; well sits two bits higher in the row word so that a shifted-out piece can never look free.
;
; Relied on at entry: CS=DS=ES=SS, SP=0xfffe, colour text mode, BIOS INT 16h, the timer counter at port 0x40.
; Not relied on: any other register (see CLAIM).
        bits 16
        org 0x100
BOARD_ROWS equ 0x18

start:
        xor di, di                  ; the board starts at offset 0: the first 50 bytes of the PSP
        mov ax, 0x400f              ; an empty row: walls only (bit 14 on the left, bits 3..0 on the right)
        mov cx, BOARD_ROWS
        repne stosw                 ; 24 rows; cx = 0 afterwards
        dec cx                      ; cx = 0xFFFF
        or [di], cx                 ; the row after the last one = 0xFFFF: the floor

        push 0xb800
        pop es                      ; es = the screen from here on (the board is only touched through ds)

next_piece:
        test si, si
        js next_piece               ; game over: the piece landed above the board (si = -2); stay here, board on screen
        ; ---- remove full rows (si = row pointer; first pass reads from the program itself)
scan:   cmp word [si], 0x7fff
        ja pick                     ; reached the floor (0xFFFF > 0x7FFF): done
        jne advance
.shift: mov ax, [si - 2]            ; a full row: copy every row above it down by one (backwards)
        mov [si], ax
        dec si
        dec si
        jne .shift                  ; (si is back at the top row, 0, now, so the scan carries on from there)
advance:
        lodsw                       ; next row
        jmp scan

pick:   in al, 0x40                 ; random piece from the timer: 0..6
        aam 7
        mov bx, pieces
        xlat                        ; one byte = rows 0 and 1 of the piece's 4x4 box
        cbw                         ; (no piece byte has bit 7 set)
        xchg dx, ax                 ; dx = the 4x4 mask
        mov cl, 7                   ; column shift: start in the middle
        xor si, si                  ; si = the piece's top row = the top row of the board

frame:  call test_piece             ; ZF=1 if the piece fits at si, cl
        pushf
        je .fits
        dec si                      ; (a collision: step back up a row)
        dec si
.fits:  mov al, 0x31                ; opcode 'xor [si],ax': stamp the piece (the cells are empty, so xor = or)
        call set_op
        pusha                       ; ---- draw the whole board: 25 rows x 15 cells x 2 columns
        xor si, si                  ; (si walks down the board)
        mov cx, BOARD_ROWS + 1
.row:   xor al, al                  ; a blank character: only the background colour shows
        mov dx, 0x4000
.cell:  test [si], dx
        lahf                        ; the attribute comes from the flags: ZF (bit 6) = empty = red, else black
        stosw
        stosw
        shr dx, 1
        jne .cell
        add di, 0x64                ; down a screen row (160 - 60 bytes)
        lodsw                       ; next board row (ax is overwritten, the blank character is made again at .row)
        loop .row
        popa
        popf
        jne next_piece              ; the piece collided: it has landed. next piece (and full rows go)
        call set_op                 ; (al is still 0x31) xor the piece out of the board again
        add ch, 2                   ; gravity: every 128th pass the piece moves down a row
        jae .nodrop
        lodsw
.nodrop:
        mov ah, 1
        int 0x16
        jz frame                    ; no key: next pass
        push cx                     ; a key: save cx/dx (a move that does not fit is taken back), handle it
        push dx
        mov ax, di
        int 0x16
        sub al, 'j'                 ; j, k, l -> 0, 1, 2
        cmp al, 3
        jae undo                    ; any other key: nothing happens
        dec al                      ; j, k, l -> -1, 0, +1
        jne sideways
rotate:                             ; dx = mask -> dx = mask turned 90 degrees (di is 0 now, and 0 again at the end)
        mov bp, 4                   ; four columns
.col:   mov ax, dx
        and ax, 0x1111              ; this column: bits 0, 4, 8, 12
        imul ax, ax, 0x1248         ; the multiply gathers them, in order, into bits 12..15 (no carries meet)
        shr ax, 12
        shl di, 4                   ; (the first column ends up in the top nibble)
        or di, ax
        shr dx, 1                   ; next column
        dec bp
        jnz .col
        mov dx, di
move:   call test_piece
        jne undo
        pop ax                      ; it fits: throw away the saved cx/dx
        pop ax
        jmp frame
undo:   pop dx
        pop cx
        jmp frame
sideways:
        sub cl, al                  ; j (-1): one column left (shift up), l (+1): one column right
        jmp move

test_piece:
        mov al, 0x23                ; opcode 'and ax,[si]'
set_op: mov [op], al                ; (self-modifying: the opcode byte below is patched)
        xor di, di                  ; di collects the cells that collide; the caller gets di = 0 back
        pusha
nib:    mov ax, dx
        and ax, 0xf
        shl ax, cl
op:     and [si], ax
        or di, ax
        lodsw
        shr dx, 4
        jne nib
        or di, di
        popa
        ret

pieces: db 0x0f, 0x66, 0x72, 0x36, 0x63, 0x74, 0x71   ; I O T S Z L J: row 0 in the low nibble, row 1 in the high
